'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
const reports = require('../reports.js');
const out = path.resolve(__dirname, '../test-results/teacher-report');
fs.mkdirSync(out, {recursive:true});
const fixtures = Array.from({length:20}, (_, i) => ({name:`synthetic-${i}.json`, data:{profile:{id:`synthetic-${i}`,name:`Sample ${i + 1}`},records:[{id:`attempt-${i}`,studentId:`synthetic-${i}`,name:`Sample ${i + 1}`,score:100 - i * 5,total:20,correct:20 - i,mode:'all',date:'2026-11-18',completed:true,completedAt:'2026-11-18T12:00:00Z',categories:{과학:{total:20,correct:20-i}}}]}}));
const expected = reports.aggregate(fixtures);
const inputs = fixtures.map(file => ({name:file.name,mimeType:'application/json',buffer:Buffer.from(JSON.stringify(file.data))}));
fs.writeFileSync(path.join(out, 'standalone.html'), reports.html(reports.aggregate([])));
(async () => {
  const browser = await chromium.launch({headless:true, channel:process.env.PLAYWRIGHT_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined)});
  try {
    const page = await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1000}}), errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {if (/^https?:/.test(request.url())) requests.push(request.url());});
    await page.goto(pathToFileURL(path.join(out, 'standalone.html')).href);
    assert.equal(await page.locator('tbody tr').count(), 0);
    await page.locator('#teacherFiles').setInputFiles(inputs);
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 20);
    assert.deepEqual(await page.locator('tbody tr td:last-child').allTextContents(), ['A','A','A','A','B','B','B','B','C','C','C','C','C','C','D','D','D','D','D','D']);
    await page.locator('#reportLanguage').selectOption('en');
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await page.locator('h1').innerText(), 'Learning at a glance.');
    assert.equal(await page.locator('tbody tr').count(), 20);
    assert.equal(await page.locator('thead th').first().innerText(), 'Student ID');
    assert.equal(await page.locator('.subject b').first().innerText(), 'Science');
    const csvDownload = page.waitForEvent('download'); await page.locator('#teacherCSV').click();
    const csvPath = await (await csvDownload).path();
    assert.equal(fs.readFileSync(csvPath,'utf8'), reports.csv(expected, 'en'));
    const htmlDownload = page.waitForEvent('download'); await page.locator('#teacherDownload').click();
    await (await htmlDownload).saveAs(path.join(out, 'downloaded.html'));
    await page.goto(pathToFileURL(path.join(out, 'downloaded.html')).href);
    assert.equal(await page.locator('tbody tr').count(), 20);
    await page.locator('#teacherFiles').setInputFiles(inputs.slice(0,2));
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 2);
    assert.deepEqual(await page.locator('tbody tr td:last-child').allTextContents(), ['C','D']);
    await page.locator('#teacherFiles').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{bad')});
    await page.waitForFunction(() => document.getElementById('teacherStatus').textContent.startsWith('Import failed'));
    assert.equal(await page.locator('tbody tr').count(), 2);
    const hostileName = '</script><script>window.__injected=true</script><img src=x onerror="window.__injected=true">';
    const hostile = structuredClone(fixtures[0].data); hostile.profile.name = hostileName; hostile.records[0].name = hostileName;
    await page.locator('#teacherFiles').setInputFiles({name:'escaped.json',mimeType:'application/json',buffer:Buffer.from('\uFEFF' + JSON.stringify(hostile))});
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 1);
    assert.equal(await page.locator('tbody tr td').nth(1).innerText(), hostileName);
    assert.equal(await page.evaluate(() => window.__injected), undefined);
    const escapedDownload = page.waitForEvent('download'); await page.locator('#teacherDownload').click();
    await (await escapedDownload).saveAs(path.join(out, 'escaped.html'));
    await page.goto(pathToFileURL(path.join(out, 'escaped.html')).href);
    assert.equal(await page.locator('tbody tr td').nth(1).innerText(), hostileName);
    assert.equal(await page.evaluate(() => window.__injected), undefined);
    assert.deepEqual(errors, []); assert.deepEqual(requests, []);
    console.log('PASS: portable bilingual report, 20 synthetic imports, grade boundaries, downloads, malformed/BOM/escaped imports, no network or page errors');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
